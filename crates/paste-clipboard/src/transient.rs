/// Checks OS clipboard metadata formats to skip concealed password-manager
/// or transient clipboard writes (e.g. 1Password, Bitwarden, KeePass).
pub fn is_current_clipboard_transient_or_concealed() -> bool {
    #[cfg(target_os = "windows")]
    {
        windows_is_transient()
    }
    #[cfg(not(target_os = "windows"))]
    {
        false
    }
}

#[cfg(target_os = "windows")]
fn windows_is_transient() -> bool {
    use std::ffi::OsStr;
    use std::os::windows::ffi::OsStrExt;
    use windows_sys::Win32::System::DataExchange::{
        IsClipboardFormatAvailable, RegisterClipboardFormatW,
    };

    const TRANSIENT_FORMATS: &[&str] = &[
        "ExcludeClipboardContentFromMonitorProcessing",
        "CanIncludeInClipboardHistory",
        "Clipboard Viewer Ignore",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.AutoGeneratedType",
    ];

    for fmt_name in TRANSIENT_FORMATS {
        let wide: Vec<u16> = OsStr::new(fmt_name)
            .encode_wide()
            .chain(std::iter::once(0))
            .collect();
        unsafe {
            let fmt_id = RegisterClipboardFormatW(wide.as_ptr());
            if fmt_id != 0 && IsClipboardFormatAvailable(fmt_id) != 0 {
                return true;
            }
        }
    }
    false
}
