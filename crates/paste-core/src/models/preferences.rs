use serde::{Deserialize, Serialize};

/// History retention window matching Paste's `_capacity` preference.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum HistoryCapacity {
    OneDay,
    SevenDays,
    ThirtyDays,
    ThreeMonths,
    OneYear,
    Forever,
}

impl HistoryCapacity {
    pub fn retention_millis(&self) -> Option<i64> {
        const DAY_MS: i64 = 86_400_000;
        match self {
            Self::OneDay => Some(DAY_MS),
            Self::SevenDays => Some(7 * DAY_MS),
            Self::ThirtyDays => Some(30 * DAY_MS),
            Self::ThreeMonths => Some(90 * DAY_MS),
            Self::OneYear => Some(365 * DAY_MS),
            Self::Forever => None,
        }
    }

    pub fn label(&self) -> &'static str {
        match self {
            Self::OneDay => "1 Day",
            Self::SevenDays => "7 Days",
            Self::ThirtyDays => "30 Days",
            Self::ThreeMonths => "3 Months",
            Self::OneYear => "1 Year",
            Self::Forever => "Forever",
        }
    }

    pub fn all() -> &'static [HistoryCapacity] {
        &[
            Self::OneDay,
            Self::SevenDays,
            Self::ThirtyDays,
            Self::ThreeMonths,
            Self::OneYear,
            Self::Forever,
        ]
    }
}

/// Application preferences mirroring Paste's `UserDefaults` keys.
#[derive(Debug, Clone, Serialize, Deserialize)]
